export type EditorTranslate = (
  key: EditorTranslationKey,
  params?: EditorTranslationParams,
  defaultMessage?: string,
) => string;

export function translateEditorLabel(
  translate: EditorTranslate | undefined,
  key: EditorTranslationKey,
  defaultMessage: string,
  params?: EditorTranslationParams,
): string {
  return translate?.(key, params, defaultMessage) ?? defaultMessage;
}
