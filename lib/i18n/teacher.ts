export function getTeacherCopy(locale: string): TeacherCopy {
  return locale.startsWith('zh') ? zh : en;
}

export function teacherResourceFor(locale: string): Record<string, string> {
  return {
    ...getTeacherCopy(locale),
    gradeValue: locale.startsWith('zh') ? '{{grade}} 年级' : 'Grade {{grade}}',
  };
}
